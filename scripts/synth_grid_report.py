"""Read the Track 2 p-hop grid by the rules fixed in the spec (2026-09-14 §5, amendment 2026-10-12).

Generates results/synth/grid-p_hop.md from results/synth/synth-p_hop-p*.json. Never hand-edit
the output; change the results or this script and regenerate.

    uv run python scripts/synth_grid_report.py
"""

from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

ARMS = (("A0", 1), ("A2", 2), ("A1u1", 2), ("A1u1", 4), ("A0", 2), ("A0", 4))
ROLE = {("A0", 1): "unshared, 12d²", ("A2", 2): "W+Wᵀ, 12d²", ("A1u1", 2): "looped ×2, 12d²",
        ("A1u1", 4): "looped ×4, 12d²", ("A0", 2): "unshared, 24d² (ref)", ("A0", 4): "unshared, 48d² (ref)"}
SHARED = (("A2", 2), ("A1u1", 2), ("A1u1", 4))
FLOOR, TOLERANCE_PP, EDGE_PP = 32.0, 5.0, 5.0


def name(arm: tuple[str, int]) -> str:
    return f"{arm[0]}@L{arm[1]}"


def load(results_dir: Path, suffix: str = "") -> dict:
    """{(p, arm, layers): {seed: accuracy in %}} for run IDs with exactly this suffix tag.

    synth-p_hop-p8-L4-A1u1-s1337 is a grid run (suffix ""); ...-s1337-80k is the 80k rerun."""
    table: dict = {}
    for path in sorted(results_dir.glob("synth-p_hop-p*.json")):
        r = json.loads(path.read_text(encoding="utf-8"))
        parts = r["run_id"].split("-")
        if "-".join(parts[6:]) != suffix:
            continue
        table.setdefault((r["difficulty"], parts[4], r["n_layer"]), {})[r["seed"]] = 100 * r["accuracy"]
    return table


def paired(a: dict, b: dict) -> tuple[list[float], float, float]:
    diffs = [a[s] - b[s] for s in sorted(a)]
    se = statistics.stdev(diffs) / len(diffs) ** 0.5 if len(diffs) > 1 else float("nan")
    return diffs, statistics.mean(diffs), se


def hl_verdict(a: dict, b: dict) -> tuple[str, list[float], float, float, float, float]:
    """The H-L rule for A2@L2 (a) vs A1u1@L2 (b)."""
    diffs, mean, se = paired(a, b)
    ma, mb = statistics.mean(a.values()), statistics.mean(b.values())
    if all(m <= FLOOR + EDGE_PP for m in (ma, mb)) or all(m >= 100 - EDGE_PP for m in (ma, mb)):
        verdict = "uninformative (both at the " + ("floor" if ma < 50 else "ceiling") + ")"
    elif (all(d > 0 for d in diffs) or all(d < 0 for d in diffs)) and abs(mean) > 2 * se:
        verdict = "**" + ("W+Wᵀ beats looping" if mean > 0 else "looping beats W+Wᵀ") + "**"
    else:
        verdict = "no difference detected"
    return verdict, diffs, mean, se, ma, mb


def render_long(grid: dict, long: dict) -> list[str]:
    """p=4 at 80k steps (spec amendment 2026-10-13): the H-L rule, unchanged, on the 80k accuracies."""
    seeds = sorted({s for v in long.values() for s in v})
    out = ["", "## 4. p=4 at 80k steps (4× the grid's budget)", "",
           "Depth-2 arms only, same recipe. Mean over seeds, per-seed values in brackets.", "",
           "| arm | 20k steps | 80k steps |", "|---|---|---|"]
    for arm in (("A2", 2), ("A1u1", 2), ("A0", 2)):
        g, l = grid[(4, *arm)], long[(4, *arm)]
        out.append(f"| `{name(arm)}` | {statistics.mean(g.values()):.1f} [{', '.join(f'{g[s]:.1f}' for s in seeds)}] | "
                   f"{statistics.mean(l.values()):.1f} [{', '.join(f'{l[s]:.1f}' for s in seeds)}] |")
    verdict, diffs, mean, se, _, _ = hl_verdict(long[(4, "A2", 2)], long[(4, "A1u1", 2)])
    out += ["", f"H-L at 80k, `A2@L2` − `A1u1@L2`: mean {mean:+.1f} pp, per seed "
                f"{', '.join(f'{d:+.1f}' for d in diffs)}, SE {se:.1f} → {verdict}."]
    return out


def render(table: dict, long: dict | None = None) -> str:
    levels = sorted({k[0] for k in table})
    seeds = sorted({s for v in table.values() for s in v})
    out = ["# Track 2 — p-hop grid", "",
           "Generated by `scripts/synth_grid_report.py` from `results/synth/synth-p_hop-p*.json`. Do not edit.",
           "", "PHopTask (alphabet 4, length 64, dense training targets), d=128, k=1, 20k steps, batch 128.",
           f"Exact-match accuracy (%) on 2,000 held-out problems; seeds {', '.join(map(str, seeds))}. "
           f"Chance is 25%; hop-free strategies reach about {FLOOR:.0f}%.", ""]

    out += ["## Accuracy, mean over seeds (per-seed values in brackets)", "",
            "| arm | stored | " + " | ".join(f"p={p}" for p in levels) + " |", "|---|---|" + "---|" * len(levels)]
    for arm in ARMS:
        cells = []
        for p in levels:
            v = table[(p, *arm)]
            cells.append(f"{statistics.mean(v.values()):.1f} [{', '.join(f'{v[s]:.1f}' for s in seeds)}]")
        out.append(f"| `{name(arm)}` | {ROLE[arm]} | " + " | ".join(cells) + " |")

    out += ["", "## 1. Validity check (p=8): looped `A1u1@L4` within 5 pp of unshared `A0@L4`", ""]
    hard = max(levels)
    looped, deep = table[(hard, "A1u1", 4)], table[(hard, "A0", 4)]
    gap = statistics.mean(deep.values()) - statistics.mean(looped.values())
    valid = abs(gap) <= TOLERANCE_PP
    out.append(f"`A0@L4` {statistics.mean(deep.values()):.1f}%, `A1u1@L4` {statistics.mean(looped.values()):.1f}%: "
               f"gap {gap:+.1f} pp → **{'passes' if valid else 'FAILS'}**.")
    if not valid:
        out.append("By the pre-registered rule, the W+Wᵀ comparisons below are reported but not interpreted.")

    out += ["", "## 2. H-C: does a same-storage shared arm beat unshared `A0@L1`?", "",
            "Supported iff the mean is higher and the sign holds in every paired seed.", "",
            "| level | arm | mean diff (pp) | per seed | verdict |", "|---|---|---|---|---|"]
    for p in levels:
        for arm in SHARED:
            diffs, mean, _ = paired(table[(p, *arm)], table[(p, "A0", 1)])
            ok = mean > 0 and all(d > 0 for d in diffs)
            out.append(f"| p={p} | `{name(arm)}` | {mean:+.1f} | {', '.join(f'{d:+.1f}' for d in diffs)} | "
                       f"{'**supported**' if ok else 'not supported'} |")

    out += ["", "## 3. H-L: `A2@L2` vs `A1u1@L2` (same storage, depth and compute)", "",
            "\"X beats Y\" iff the sign holds in all seeds and |mean| > 2 SE. A level where both arms are within "
            f"{EDGE_PP:.0f} points of the floor ({FLOOR:.0f}%) or of 100% is uninformative.", "",
            "| level | `A2@L2` | `A1u1@L2` | mean diff A2 − A1u1 (pp) | per seed | SE | verdict |", "|---|---|---|---|---|---|---|"]
    for p in levels:
        verdict, diffs, mean, se, ma, mb = hl_verdict(table[(p, "A2", 2)], table[(p, "A1u1", 2)])
        out.append(f"| p={p} | {ma:.1f} | {mb:.1f} | {mean:+.1f} | {', '.join(f'{d:+.1f}' for d in diffs)} | "
                   f"{se:.1f} | {verdict} |")
    if long:
        out += render_long(table, long)
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", default="results/synth")
    args = ap.parse_args()
    text = render(load(Path(args.results)), load(Path(args.results), suffix="80k"))
    (Path(args.results) / "grid-p_hop.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
